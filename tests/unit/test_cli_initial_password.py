"""CLI 初始口令接线测试（Feature 18：serve 首启 / set-password / 横幅回显）。

密钥库经 ``rdc.server.initial_password.get_secret_store`` 打桩为内存替身，
数据根经 ``tmp_app_dir`` 隔离——**绝不触真实 DPAPI、绝不写真实 config**。
被控端真实起服务的路径用 ``_run_serve_headless`` 打桩规避（不占端口、不起 TLS）。
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest

import rdc.cli as cli
import rdc.server.initial_password as ip
from rdc.config import settings as sm
from rdc.secrets.factory import StoreSelection


class _MemStore:
    def __init__(self) -> None:
        self.data: dict[str, str] = {}

    @property
    def name(self) -> str:
        return "mem"

    def available(self) -> bool:
        return True

    def save(self, key: str, value: str) -> None:
        self.data[key] = value

    def load(self, key: str) -> str | None:
        return self.data.get(key)

    def delete(self, key: str) -> None:
        self.data.pop(key, None)


@pytest.fixture
def mem_store(monkeypatch: pytest.MonkeyPatch) -> _MemStore:
    store = _MemStore()
    monkeypatch.setattr(
        ip,
        "get_secret_store",
        lambda *a, **k: StoreSelection(store=store, degraded=False, reason=""),
    )
    return store


@pytest.fixture
def capture_headless(monkeypatch: pytest.MonkeyPatch) -> dict[str, Any]:
    """打桩 headless/tray 两条真实起服务路径，捕获入参，避免真起 TLS。"""
    seen: dict[str, Any] = {}

    def _fake_headless(settings: Any, *, silent: bool = False) -> int:
        seen["settings"] = settings
        seen["silent"] = silent
        return 0

    monkeypatch.setattr(cli, "_run_serve_headless", _fake_headless)
    monkeypatch.setattr(
        cli, "_run_gui_with", lambda session, settings: seen.__setitem__("tray", settings) or 0
    )
    return seen


class TestServeFirstRun:
    def test_generates_and_persists_on_default_config(
        self, tmp_app_dir: Path, mem_store: _MemStore, capture_headless: dict[str, Any]
    ) -> None:
        sm.reset_for_test()
        try:
            rc = cli.main(["serve"])
        finally:
            sm.reset_for_test()
        assert rc == 0
        cfg = json.loads((tmp_app_dir / "config.json").read_text(encoding="utf-8"))
        assert cfg["password_hash"]  # 已落 bcrypt 哈希
        assert cfg["password_autogenerated"] is True
        assert mem_store.data[ip.INITIAL_PASSWORD_SECRET_KEY]  # 明文进密钥库
        assert cfg["password_hash"] != mem_store.data[ip.INITIAL_PASSWORD_SECRET_KEY]

    def test_writes_back_to_custom_config_path(
        self,
        tmp_app_dir: Path,
        mem_store: _MemStore,
        capture_headless: dict[str, Any],
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        """--config 场景：生成的口令必须写回该文件，不是默认位置（否则丢口令）。"""
        custom = tmp_app_dir / "other" / "portable.json"
        custom.parent.mkdir(parents=True, exist_ok=True)
        saved_paths: list[Path | None] = []
        orig = sm.save_settings

        def _spy(s: Any, path: Path | None = None) -> None:
            saved_paths.append(path)
            orig(s, path)

        monkeypatch.setattr(sm, "save_settings", _spy)
        cli.main(["serve", "--config", str(custom)])
        assert custom in saved_paths
        assert json.loads(custom.read_text(encoding="utf-8"))["password_autogenerated"] is True

    def test_existing_password_not_regenerated(
        self, tmp_app_dir: Path, mem_store: _MemStore, capture_headless: dict[str, Any]
    ) -> None:
        sm.save_settings(sm.Settings(password_hash="bcrypt$keep"), tmp_app_dir / "config.json")
        cli.main(["serve"])
        assert mem_store.data.get(ip.INITIAL_PASSWORD_SECRET_KEY) is None

    def test_silent_flag_forwarded(
        self, tmp_app_dir: Path, mem_store: _MemStore, capture_headless: dict[str, Any]
    ) -> None:
        """Feature 17：serve --silent → headless 收到 silent=True（不打印横幅）。"""
        sm.reset_for_test()
        try:
            cli.main(["serve", "--silent"])
        finally:
            sm.reset_for_test()
        assert capture_headless["silent"] is True


class TestSetPasswordClearsAutogen:
    def test_marks_user_set_and_deletes_plaintext(
        self, tmp_app_dir: Path, mem_store: _MemStore, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        sm.reset_for_test()
        s = sm.Settings()
        ip.ensure_host_password(s)
        sm.save_settings(s, tmp_app_dir / "config.json")
        assert mem_store.data.get(ip.INITIAL_PASSWORD_SECRET_KEY)
        monkeypatch.setattr(
            cli, "stdin_is_tty", lambda: False
        )  # 走 --password 非交互分支
        rc = cli.main(["set-password", "--password", "MyPass123"])
        assert rc == 0
        cfg = json.loads((tmp_app_dir / "config.json").read_text(encoding="utf-8"))
        assert cfg["password_autogenerated"] is False
        assert mem_store.data.get(ip.INITIAL_PASSWORD_SECRET_KEY) is None  # 明文已删


class TestBannerNotice:
    def test_banner_shows_plaintext_when_autogenerated(
        self, mem_store: _MemStore, capsys: pytest.CaptureFixture[str]
    ) -> None:
        s = sm.Settings()
        pw = ip.ensure_host_password(s).password
        cli._print_host_banner(object(), s)  # noqa: SLF001
        out = capsys.readouterr().out
        assert pw in out and "初始密码" in out

    def test_banner_omits_notice_for_user_password(
        self, mem_store: _MemStore, capsys: pytest.CaptureFixture[str]
    ) -> None:
        s = sm.Settings(password_hash="bcrypt$set", password_autogenerated=False)
        cli._print_host_banner(object(), s)  # noqa: SLF001
        assert "初始密码" not in capsys.readouterr().out

    def test_notice_render_failure_does_not_crash_banner(
        self, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
    ) -> None:
        """回显函数抛错不得让已启动的被控端崩溃（约束 6：降级 warning 而非炸）。"""
        def _boom(_settings: Any) -> str:
            raise RuntimeError("密钥库挂了")

        monkeypatch.setattr(ip, "initial_notice_text", _boom)
        s = sm.Settings(password_hash="bcrypt$set", password_autogenerated=True)
        cli._print_host_banner(object(), s)  # noqa: SLF001
        assert "被控端已启动" in capsys.readouterr().out
