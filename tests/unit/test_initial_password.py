class TestEnsure:
    def test_first_run_generates_and_stores(self, mem_store: _MemStore) -> None:
        s = Settings()
        assert s.password_hash == ""
        result = ip.ensure_host_password(s)
        assert result.created is True
        assert len(result.password) == 8
        assert s.password_hash  # bcrypt 已落（非明文）
        assert s.password_autogenerated is True
        # 明文进密钥库、不进 password_hash
        assert mem_store.data[ip.INITIAL_PASSWORD_SECRET_KEY] == result.password
        assert result.password not in s.password_hash

    def test_existing_password_noop(self, mem_store: _MemStore) -> None:
        s = Settings(password_hash="bcrypt$already$set")
        result = ip.ensure_host_password(s)
        assert result.created is False
        assert result.password == ""
        assert mem_store.saved == []

    def test_store_unavailable_still_sets_hash(self, no_store: None) -> None:
        """密钥库炸了：口令照常生成+落库（哈希），只是无法回显明文，绝不崩。"""
        s = Settings()
        result = ip.ensure_host_password(s)
        assert result.created is True
        assert s.password_hash
        assert s.password_autogenerated is True

    def test_load_gated_on_autogenerated(self, mem_store: _MemStore) -> None:
        s = Settings()
        result = ip.ensure_host_password(s)
        assert ip.load_initial_password(s) == result.password
        s.password_autogenerated = False  # 模拟用户已改口令
        assert ip.load_initial_password(s) == ""


