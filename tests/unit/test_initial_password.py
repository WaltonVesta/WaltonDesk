class TestGenerate:
    def test_satisfies_policy_and_composition(self) -> None:
        pw = generate_initial_password()
        assert len(pw) == 8
        assert check_password(pw) == []  # 满足强度策略（≥8 + 字母 + 数字）
        assert any(c.isupper() for c in pw)
        assert any(c.islower() for c in pw)
        assert any(c.isdigit() for c in pw)

    def test_no_confusable_glyphs(self) -> None:
        """排除 0/O/1/I/l，抄写友好（Feature 18 降低真人抄错成本）。"""
        pw = generate_initial_password()
        assert not set(pw) & set("0O1Il")

    def test_randomness_across_calls(self) -> None:
        """两次生成大概率不同（8 位空间，连撞 6 次才判失败，误红概率极低）。"""
        seen = {generate_initial_password() for _ in range(6)}
        assert len(seen) >= 2

    def test_too_short_rejected(self) -> None:
        with pytest.raises(ValueError, match="至少 3 位"):
            generate_initial_password(2)


