"""初始口令策略（rdc.server.initial_password + generate_initial_password）单元测试。

走查第十二批 Feature 18。全程 monkeypatch ``get_secret_store`` 注入内存替身，
**绝不触真实 DPAPI/密钥库**；路径经 ``tmp_app_dir`` 隔离到 pytest 临时目录。

覆盖：随机口令满足强度策略与字符构成、ensure 幂等（有口令不动）、密钥库
不可用降级不崩、load/notice 的状态位门控、mark/suppress 位翻转。
"""

from __future__ import annotations

import pytest

import rdc.server.initial_password as ip
from rdc.config.settings import Settings
from rdc.secrets.factory import StoreSelection
from rdc.secrets.password import generate_initial_password
from rdc.security.password_policy import check_password


class _MemStore:
    """内存 SecretStore 替身（记录三操作，零 IO）。"""

    def __init__(self) -> None:
        self.data: dict[str, str] = {}
        self.saved: list[tuple[str, str]] = []
        self.deleted: list[str] = []

    @property
    def name(self) -> str:
        return "mem"

    def available(self) -> bool:
        return True

    def save(self, key: str, value: str) -> None:
        self.data[key] = value
        self.saved.append((key, value))

    def load(self, key: str) -> str | None:
        return self.data.get(key)

    def delete(self, key: str) -> None:
        self.data.pop(key, None)
        self.deleted.append(key)


@pytest.fixture
def mem_store(monkeypatch: pytest.MonkeyPatch) -> _MemStore:
    store = _MemStore()
    monkeypatch.setattr(
        ip, "get_secret_store", lambda *a, **k: StoreSelection(store=store, degraded=False, reason="")
    )
    return store


@pytest.fixture
def no_store(monkeypatch: pytest.MonkeyPatch) -> None:
    def _boom(*a: object, **k: object) -> StoreSelection:
        raise RuntimeError("密钥库探测炸了")

    monkeypatch.setattr(ip, "get_secret_store", _boom)


