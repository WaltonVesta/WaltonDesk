"""被控端初始口令策略（走查第十二批 Feature 18）。

首次运行（``Settings.password_hash`` 为空）时自动生成一个随机 8 位强口令并
bcrypt 落库，避免"未设口令 → 任意口令通过"的裸奔默认态；同时把明文交给
平台密钥库（Windows=DPAPI）保存，供被控端启动时在控制台 / Launcher / 托盘
气泡回显，用户改成自己的口令后即清除。

设计口径：

- **明文绝不进 ``config.json``**（该文件按渗透清单 S4 判定为"外部可写"面，
  也是备份/排障时会被随手发出去的东西）。明文只经
  :func:`rdc.secrets.get_secret_store` 落平台密钥库；密钥库不可用时
  **不降级为明文落盘**——只记 warning 并放弃回显能力（用户仍可用
  ``rdc set-password`` 或托盘"修改密码"自行设定）。
- :func:`ensure_host_password` 纯同步、零 Qt、零网络，CLI 与 UI 共用同一入口；
  是否落盘由调用方决定（本模块只改传入的 settings 对象并返回结果），便于测试。
- 状态位 ``password_autogenerated`` 让"当前口令是不是系统生成的"成为可判定
  事实，用户自行设置口令（CLI/UI/托盘任一入口）都必须清掉它。
"""

from __future__ import annotations

from dataclasses import dataclass

from rdc.config.settings import Settings
from rdc.logging import get_logger
from rdc.secrets.base import SecretStore
from rdc.secrets.factory import get_secret_store
from rdc.secrets.password import generate_initial_password, hash_password

__all__ = [
    "INITIAL_PASSWORD_SECRET_KEY",
    "InitialPasswordResult",
    "clear_initial_password",
    "ensure_host_password",
    "first_run_notice_text",
    "initial_notice_text",
    "load_initial_password",
    "mark_password_user_set",
    "suppress_initial_notice",
]

_LOG = get_logger("server.initial_password")

#: 明文在平台密钥库中的键名（常量，非凭据值）。
INITIAL_PASSWORD_SECRET_KEY = "rdc-initial-password"  # nosec B105 -- 密钥库键名常量，非凭据值


@dataclass(frozen=True)
class InitialPasswordResult:
    """一次 :func:`ensure_host_password` 的结果。

    Attributes:
        created: 本次是否新生成了口令（False = 配置里已有口令，什么都不做）。
        password: 新生成的明文口令；密钥库写入失败时仍返回明文（本次会话
            可打印），但 :func:`load_initial_password` 后续取不到。
    """

    created: bool
    password: str = ""


def _store() -> SecretStore | None:
    """取平台密钥库；不可用时返回 ``None`` 并留痕（不静默、不降级明文落盘）。"""
    try:
        selection = get_secret_store()
    except Exception as exc:  # noqa: BLE001 - 后端探测异常面宽（dbus/钥匙串/DPAPI）
        _LOG.warning("secret_store_probe_failed", error=repr(exc))
        return None
    if selection.degraded:
        _LOG.info("secret_store_degraded", reason=selection.reason)
    return selection.store


def ensure_host_password(settings: Settings) -> InitialPasswordResult:
    """配置无口令时生成随机强口令并写入 ``settings``（**不落盘，调用方保存**）。

    Args:
        settings: 运行时配置（原地更新 ``password_hash`` /
            ``password_autogenerated``）。

    Returns:
        :class:`InitialPasswordResult`；``created=False`` 表示已有口令、
        本函数无任何副作用。
    """
    if settings.password_hash:
        return InitialPasswordResult(created=False)
    password = generate_initial_password()
    settings.password_hash = hash_password(password)
    settings.password_autogenerated = True
    store = _store()
    if store is not None:
        try:
            store.save(INITIAL_PASSWORD_SECRET_KEY, password)
        except Exception as exc:  # noqa: BLE001 - 明文存不进密钥库只影响"下次回显"
            _LOG.error("initial_password_store_failed", error=repr(exc))
    else:
        _LOG.error("initial_password_not_persisted_cleartext", hint="仅本次会话可显示")
    _LOG.info("initial_password_generated")  # 只记事件，绝不记口令
    return InitialPasswordResult(created=True, password=password)


def load_initial_password(settings: Settings) -> str:
    """取回当前生效的初始口令明文（非自动生成态/取不到 → 空串）。

    仅当 ``password_autogenerated`` 为真才尝试读取——用户改过口令后，即使
    密钥库里还有残留，也必须当作"没有初始口令"，避免展示已失效的旧明文。
    """
    if not settings.password_autogenerated:
        return ""
    store = _store()
    if store is None:
        return ""
    try:
        return store.load(INITIAL_PASSWORD_SECRET_KEY) or ""
    except Exception as exc:  # noqa: BLE001 - 读失败降级为"无法回显"，不影响服务
        _LOG.warning("initial_password_load_failed", error=repr(exc))
        return ""


def clear_initial_password() -> None:
    """删除密钥库里的初始口令明文（用户改口令后调用；幂等，失败留痕）。"""
    store = _store()
    if store is None:
        return
    try:
        store.delete(INITIAL_PASSWORD_SECRET_KEY)
    except Exception as exc:  # noqa: BLE001 - 清理失败不阻断改口令主流程
        _LOG.warning("initial_password_clear_failed", error=repr(exc))


def mark_password_user_set(settings: Settings) -> Settings:
    """把口令标记为"用户自行设置"（任一改口令入口共用，**不落盘**）。

    清三件事：自动生成位归 False（停止启动回显提示）、密钥库明文删除、
    "不再提示"位一并复位（下次再回到自动生成态时提示应重新出现）。
    调用方随后自行 ``save_settings``。
    """
    settings.password_autogenerated = False
    settings.initial_password_notice_suppressed = False
    clear_initial_password()
    _LOG.info("password_marked_user_set")
    return settings


def suppress_initial_notice(settings: Settings) -> Settings:
    """勾选"不再提示"（调用方随后自行 ``save_settings``）。"""
    settings.initial_password_notice_suppressed = True
    _LOG.info("initial_password_notice_suppressed")
    return settings


def initial_notice_text(settings: Settings) -> str:
    """构造"初始口令提醒"文案（CLI 控制台 / Launcher 弹窗 / 托盘气泡共用）。

    仅当"当前口令是系统自动生成"**且**用户未勾选"不再提示"时返回非空文本。
    明文取自密钥库（:func:`load_initial_password`）；取不到明文（密钥库不可
    用等）时返回空串——宁可不显示，也绝不显示一个错误的口令误导用户。

    ⚠️ 本函数只适合**重启后**的回显（口令早已落库）。**首启当次**必须用
    :func:`first_run_notice_text` 直接格式化 :func:`ensure_host_password`
    返回的内存明文——走查第十三批 Bug 2：旧实现首启也走本函数从 DPAPI
    回读，回读失败（权限/服务未就绪/非 Windows）即返回空串，控制台与
    气泡双双静默，用户拿着"已生成密码"的日志却看不到密码、无法连接。
    """
    if not settings.password_autogenerated or settings.initial_password_notice_suppressed:
        return ""
    password = load_initial_password(settings)
    if not password:
        return ""
    return (
        f"当前连接口令：{password}\n\n"
        "这是系统自动生成的初始密码，请记下。建议在设置中修改为您自己的密码。"
        "勾选此处的\u201c不再提示\u201d可关闭此通知。"
    )


def first_run_notice_text(password: str) -> str:
    """首启当次的显眼回显文案（明文直接来自 :func:`ensure_host_password`）。

    与 :func:`initial_notice_text` 的唯一区别：不查密钥库——本次会话刚生成
    的明文就在参数里，DPAPI 写失败也必须让用户当场看到密码（Feature 18
    核心诉求"首启可知"）。``password`` 为空返回空串（非首启场景）。
    """
    if not password:
        return ""
    return (
        f"首次启动，已生成随机初始密码：{password}\n\n"
        "这是系统自动生成的初始密码，请记下。建议在设置中修改为您自己的密码。"
        "勾选此处的\u201c不再提示\u201d可关闭此通知。"
    )
